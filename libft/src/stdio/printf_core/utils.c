#include "libft/limits.h"

int	parse_int(char **s)
{
	int	n;

	n = 0;
	while (ft_isdigit(**s))
	{
		if (n > INT_MAX / 10U || (**s - '0') > INT_MAX - 10 * n)
			n = -1;
		else
			n = 10 * n + (**s - '0');
		++(*s);
	}
	return (n);
}
